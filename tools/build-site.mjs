#!/usr/bin/env node
// Builds the update notes from data/releases.json plus any published GitHub releases:
//   public/updates/index.html, public/updates.xml, and the "Latest update" card in public/index.html.
// No dependencies. The output is committed, so the site also works with no build.
// If GitHub can't be reached the build carries on with the JSON alone and still exits 0.
// RELEASES_API_URL overrides the GitHub URL, for testing the failure path.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SITE = "https://sasnotch.vercel.app";
const REPO = "Rsunthar2027/SasNotch";
const API_URL = process.env.RELEASES_API_URL || `https://api.github.com/repos/${REPO}/releases?per_page=100`;
const TIMEOUT_MS = 10000;

const fromRoot = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const DATA_FILE = fromRoot("data/releases.json");
const HOME_FILE = fromRoot("public/index.html");
const UPDATES_DIR = fromRoot("public/updates");
const UPDATES_FILE = fromRoot("public/updates/index.html");
const FEED_FILE = fromRoot("public/updates.xml");

const CARD_START = "<!-- latest-update:start (generated by tools/build-site.mjs from data/releases.json; don't edit by hand) -->";
const CARD_PATTERN = /<!-- latest-update:start[\s\S]*?<!-- latest-update:end -->/;
const CARD_END = "<!-- latest-update:end -->";

const VERSION = /^\d+\.\d+\.\d+$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const GROUPS = [["new", "New"], ["improved", "Improved"], ["fixed", "Fixed"]];

/* ---------- Data ---------- */

function checkEntries(entries) {
  if (!Array.isArray(entries)) throw new Error("data/releases.json must be an array");
  const seen = new Set();
  for (const entry of entries) {
    const name = entry?.version;
    if (!VERSION.test(name)) throw new Error(`bad version: ${JSON.stringify(name)}`);
    if (seen.has(name)) throw new Error(`${name} is listed twice`);
    seen.add(name);
    if (entry.date !== null && !DATE.test(entry.date)) throw new Error(`${name}: date must be YYYY-MM-DD or null`);
    if (typeof entry.title !== "string") throw new Error(`${name}: title must be a string`);
    for (const [group] of GROUPS) {
      if (!Array.isArray(entry[group]) || entry[group].some((bullet) => typeof bullet !== "string")) {
        throw new Error(`${name}: ${group} must be a list of strings`);
      }
    }
  }
  return entries;
}

async function fetchReleases() {
  try {
    const response = await fetch(API_URL, {
      headers: { Accept: "application/vnd.github+json", "User-Agent": "sasnotch-site-build" },
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const releases = await response.json();
    if (!Array.isArray(releases)) throw new Error("the response is not a list");
    console.log(`GitHub: read ${releases.length} release(s).`);
    return releases;
  } catch (error) {
    console.warn(`GitHub unavailable (${error.cause?.code || error.message}): building from data/releases.json alone.`);
    return [];
  }
}

// Markdown to plain text: the output is escaped, so links and emphasis would show as symbols.
function plainText(markdown) {
  return markdown
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/(\*\*|__|`)/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

// Bullets under ### Added/Changed/Fixed/Removed. Anything else in the body is ignored.
function parseBody(body) {
  const sections = { added: [], changed: [], removed: [], fixed: [] };
  let bullets = null;
  let open = false; // Whether the last line was a bullet that an indented line can continue.
  for (const line of String(body || "").split(/\r?\n/)) {
    const heading = /^#{1,6}\s+(.*?)\s*#*\s*$/.exec(line);
    const bullet = /^\s*[-*+]\s+(.*)$/.exec(line);
    if (heading) {
      bullets = sections[heading[1].replace(/:$/, "").toLowerCase()] || null;
      open = false;
    } else if (bullets && bullet) {
      bullets.push(bullet[1]);
      open = true;
    } else if (bullets && open && /^\s+\S/.test(line)) {
      bullets[bullets.length - 1] += ` ${line.trim()}`;
    } else {
      open = false;
    }
  }
  const clean = (list) => list.map(plainText).filter(Boolean);
  return {
    new: clean(sections.added),
    improved: [...clean(sections.changed), ...clean(sections.removed).map((text) => `Removed: ${text}`)],
    fixed: clean(sections.fixed),
  };
}

function compareVersions(a, b) {
  const left = a.version.split(".").map(Number);
  const right = b.version.split(".").map(Number);
  return right[0] - left[0] || right[1] - left[1] || right[2] - left[2];
}

function merge(entries, releases) {
  const byVersion = new Map(entries.map((entry) => [entry.version, { ...entry }]));
  for (const release of releases) {
    if (release?.draft || release?.prerelease || !release?.published_at) continue;
    const version = String(release.tag_name).replace(/^v/, "");
    if (!VERSION.test(version)) continue;
    let entry = byVersion.get(version);
    if (!entry) {
      // The release name is usually just "SasNotch 1.2.3", which the version heading already says.
      const name = String(release.name || "").trim();
      const title = name === `SasNotch ${version}` ? "" : name;
      entry = { version, date: null, title, ...parseBody(release.body) };
      byVersion.set(version, entry);
      console.log(`Added ${version} from GitHub.`);
    }
    entry.date ??= release.published_at.slice(0, 10);
    entry.published_at ??= release.published_at;
    entry.noDmg = Array.isArray(release.assets) && !release.assets.some((asset) => asset.name === "SasNotch.dmg");
  }
  return [...byVersion.values()].sort(compareVersions);
}

/* ---------- Small helpers ---------- */

const escapeHtml = (text) => String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const escapeXml = (text) => escapeHtml(String(text).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g, ""));
const permalink = (entry) => `${SITE}/updates#v${entry.version}`;
const downloadUrl = (entry) => `https://github.com/${REPO}/releases/download/v${entry.version}/SasNotch.dmg`;
const timestamp = (entry) => entry.published_at || `${entry.date}T00:00:00Z`;

function formatDate(date) {
  const [year, month, day] = date.split("-").map(Number);
  return `${day} ${MONTHS[month - 1]} ${year}`;
}

const dateHtml = (entry) => (entry.date
  ? `<time class="release-date" datetime="${entry.date}">${formatDate(entry.date)}</time>`
  : '<span class="release-date">Not out yet</span>');

/* ---------- Home page card ---------- */

function cardHtml(latest) {
  if (!latest) return `${CARD_START}\n    ${CARD_END}`;
  const bullets = GROUPS.flatMap(([group]) => latest[group]).slice(0, 3);
  const title = latest.title ? `\n          <p class="release-title">${escapeHtml(latest.title)}</p>` : "";
  return `${CARD_START}
    <section class="section section-latest" id="latest-update" aria-labelledby="latest-update-title">
      <div class="wrap wrap-narrow">
        <h2 id="latest-update-title">Latest update</h2>
        <div class="release release-latest">
          <div class="release-head">
            <h3 class="release-version">${escapeHtml(latest.version)}</h3>
            ${dateHtml(latest)}
          </div>${title}
          <ul>
${bullets.map((bullet) => `            <li>${escapeHtml(bullet)}</li>`).join("\n")}
          </ul>
          <p class="release-more"><a href="/updates">See all updates</a></p>
        </div>
      </div>
    </section>
    ${CARD_END}`;
}

/* ---------- /updates page ---------- */

function pick(html, pattern, label) {
  const match = pattern.exec(html);
  if (!match) throw new Error(`public/index.html has no ${label}`);
  return match[0];
}

// The home page's links to its own sections have to work from another page. <use href="#..."> stays.
const pointAtHome = (html) => html.replace(/(<a\b[^>]*\bhref=")#/g, "$1/#");

function releaseHtml(entry) {
  const anchor = `v${entry.version}`;
  const name = escapeHtml(entry.version);
  const title = entry.title ? `\n            <p class="release-title">${escapeHtml(entry.title)}</p>` : "";
  const groups = GROUPS.filter(([group]) => entry[group].length).map(([group, label]) => `
            <h3 class="release-group">${label}</h3>
            <ul>
${entry[group].map((bullet) => `              <li>${escapeHtml(bullet)}</li>`).join("\n")}
            </ul>`).join("");
  const download = entry.date && !entry.noDmg ? `
            <p class="release-get"><a class="btn btn-small" href="${escapeHtml(downloadUrl(entry))}" data-download><svg class="btn-icon" aria-hidden="true"><use href="#apple-dl"/></svg>Download this version</a></p>` : "";
  return `          <li class="release${entry.date ? "" : " release-next"}" id="${anchor}">
            <div class="release-head">
              <h2 class="release-version">${name}</h2>
              ${dateHtml(entry)}
              <a class="release-link" href="#${anchor}">Link<span class="sr-only"> to version ${name}</span></a>
            </div>${title}${groups}${download}
          </li>`;
}

function updatesHtml(entries, home) {
  const header = pointAtHome(pick(home, /<header class="nav"[\s\S]*?<\/header>/, "nav header"))
    .replace('href="/#top" aria-label="SasNotch, back to top"', 'href="/" aria-label="SasNotch home"')
    .replace(/<a class="nav-wide" href="\/updates">/, '<a class="nav-wide" href="/updates" aria-current="page">');
  const footer = pointAtHome(pick(home, /<footer class="footer">[\s\S]*?<\/footer>/, "footer"));
  const toast = pointAtHome(pick(home, /<div class="toast"[^\n]*<\/div>/, "toast"));
  const body = `${header}

  <main id="main">
    <section class="section section-updates" aria-labelledby="updates-title">
      <div class="wrap wrap-narrow">
        <h1 id="updates-title">What's new</h1>
        <p class="section-lede">Read what changed in each version, newest first. Follow new releases with the <a href="/updates.xml">Atom feed</a>, or see every release on <a href="https://github.com/${REPO}/releases">GitHub</a>.</p>
        <ol class="releases" role="list">
${entries.map(releaseHtml).join("\n")}
        </ol>
      </div>
    </section>
  </main>

  ${footer}
  ${toast}`;

  // Copy only the icons this page uses.
  const used = new Set([...body.matchAll(/<use href="#([\w-]+)"/g)].map((match) => match[1]));
  const symbols = [...home.matchAll(/ *<symbol id="([\w-]+)"[\s\S]*?<\/symbol>/g)]
    .filter((match) => used.has(match[1]))
    .map((match) => match[0]);
  const description = "What changed in each version of SasNotch, the free notch app for Mac.";

  return `<!doctype html>
<!-- Generated by tools/build-site.mjs from data/releases.json. Don't edit by hand. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>What's new in SasNotch</title>
  <meta name="description" content="${description}">
  <link rel="canonical" href="${SITE}/updates">
  <meta name="theme-color" content="#13281F">
  <meta name="color-scheme" content="light">

  <meta property="og:type" content="website">
  <meta property="og:site_name" content="SasNotch">
  <meta property="og:title" content="What's new in SasNotch">
  <meta property="og:description" content="${description}">
  <meta property="og:url" content="${SITE}/updates">
  <meta property="og:image" content="${SITE}/og.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="A sasquatch peeking from behind a pine tree under a MacBook notch, with the words SasNotch, a cozy little island for your Mac's notch.">
  <meta name="twitter:card" content="summary_large_image">

  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  <link rel="icon" href="/favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="/apple-touch-icon.png">
  <link rel="alternate" type="application/atom+xml" title="SasNotch updates" href="${SITE}/updates.xml">
  <link rel="preload" href="/fonts/caprasimo-latin.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="/fonts/nunito-latin.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="/css/site.css">
  <script src="/js/main.js" defer></script>
  <script src="/_vercel/insights/script.js" defer></script>
</head>
<body class="page-updates">
  <a class="skip" href="#main">Skip to content</a>

  <svg class="sprite" aria-hidden="true" focusable="false">
${symbols.join("\n")}
  </svg>

  ${body}
</body>
</html>
`;
}

/* ---------- Atom feed ---------- */

function feedContent(entry) {
  return GROUPS.filter(([group]) => entry[group].length)
    .map(([group, label]) => `<h3>${label}</h3><ul>${entry[group].map((bullet) => `<li>${escapeHtml(bullet)}</li>`).join("")}</ul>`)
    .join("");
}

function feedXml(released) {
  const updated = released.map(timestamp).sort().at(-1) || "1970-01-01T00:00:00Z";
  const items = released.map((entry) => `  <entry>
    <id>${escapeXml(permalink(entry))}</id>
    <title>${escapeXml(`SasNotch ${entry.version}${entry.title ? `: ${entry.title}` : ""}`)}</title>
    <link rel="alternate" type="text/html" href="${escapeXml(permalink(entry))}"/>
    <published>${timestamp(entry)}</published>
    <updated>${timestamp(entry)}</updated>
    <content type="html">${escapeXml(feedContent(entry))}</content>
  </entry>`);
  return `<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <id>${SITE}/updates.xml</id>
  <title>SasNotch updates</title>
  <subtitle>What changed in each version of SasNotch.</subtitle>
  <link rel="self" type="application/atom+xml" href="${SITE}/updates.xml"/>
  <link rel="alternate" type="text/html" href="${SITE}/updates"/>
  <author><name>SasNotch</name></author>
  <updated>${updated}</updated>
${items.join("\n")}
</feed>
`;
}

/* ---------- Sizes (tools/release-sizes.mjs, when that file exists) ---------- */

async function withSizes(html) {
  let sizesModule;
  try {
    sizesModule = await import("./release-sizes.mjs");
  } catch (error) {
    if (error.code !== "ERR_MODULE_NOT_FOUND") console.warn(`Skipping sizes: ${error.message}`);
    return html;
  }
  try {
    const timeout = new Promise((resolve) => setTimeout(resolve, 2 * TIMEOUT_MS, null).unref());
    const sizes = await Promise.race([sizesModule.latestSizes(), timeout]);
    if (!sizes) return html;
    const result = sizesModule.applySizes(html, sizes);
    return typeof result === "string" && result ? result : html;
  } catch (error) {
    console.warn(`Skipping sizes: ${error.message}`);
    return html;
  }
}

/* ---------- Build ---------- */

async function main() {
  const entries = checkEntries(JSON.parse(await readFile(DATA_FILE, "utf8")));
  const merged = merge(entries, await fetchReleases());
  const released = merged.filter((entry) => entry.date);

  const home = await readFile(HOME_FILE, "utf8");
  if (!CARD_PATTERN.test(home)) throw new Error("public/index.html has no latest-update markers");
  const newHome = await withSizes(home.replace(CARD_PATTERN, () => cardHtml(released[0])));

  const updates = updatesHtml(merged, newHome);
  const feed = feedXml(released);

  await mkdir(UPDATES_DIR, { recursive: true });
  await writeFile(HOME_FILE, newHome);
  await writeFile(UPDATES_FILE, updates);
  await writeFile(FEED_FILE, feed);
  console.log(`Built ${merged.length} version(s), ${released.length} released. Latest: ${released[0]?.version ?? "none"}.`);
}

main().then(() => process.exit(0), (error) => {
  // Reached only for a problem in this repo (bad JSON, missing markers), never for a network failure.
  console.error(`build-site: ${error.message}`);
  process.exit(1);
});
